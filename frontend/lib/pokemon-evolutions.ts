export function getEvolutionInfo(pokemonId: number): PokemonEvolutionInfo | undefined {
  const meta = POKEMON_EVO_META[pokemonId];
  if (!meta) return undefined;
  const [chainId, stage, evolvesFromId, isBabyNum] = meta;
  const isBaby = isBabyNum === 1;
  const stageName: EvolutionStage = isBaby ? "Baby" : stage === 0 ? "Base" : stage === 1 ? "Stage 1" : "Stage 2";
  const familyIds = EVOLUTION_FAMILIES[chainId] || [pokemonId];

  return {
    id: pokemonId,
    chainId,
    stage,
    stageName,
    evolvesFromId,
    isBaby,
    familyIds,
  };
}

export function getEvolutionFamilyIds(pokemonId: number): number[] {
  const meta = POKEMON_EVO_META[pokemonId];
  if (!meta) return [pokemonId];
  return EVOLUTION_FAMILIES[meta[0]] || [pokemonId];
}

export function getEvolutionRelation(
  targetId: number,
  directMatchedIds: Set<number>,
  getPokemonName?: (id: number) => string
): EvolutionRelation | null {
  const targetInfo = getEvolutionInfo(targetId);
  if (!targetInfo) return null;

  if (directMatchedIds.has(targetId)) {
    return {
      type: "direct",
      stageName: targetInfo.stageName,
    };
  }

  // Find which directly matched pokemon is in the same evolution family
  const familyDirectMatch = targetInfo.familyIds.find((id) => directMatchedIds.has(id));
  if (!familyDirectMatch) return null;

  const directInfo = getEvolutionInfo(familyDirectMatch);
  if (!directInfo) return null;

  const matchedName = getPokemonName ? getPokemonName(familyDirectMatch) : undefined;

  if (targetInfo.stage < directInfo.stage) {
    return {
      type: "pre-evolution",
      stageName: targetInfo.stageName,
      primaryMatchName: matchedName,
    };
  }

  return {
    type: "evolution",
    stageName: targetInfo.stageName,
    primaryMatchName: matchedName,
  };
}
